describe('signCrmRequest (invariant 6)', () => {
  // Generated by fsc-crm hmac.mjs signRequest, verified OK by its verifySignedRequest.
  const VECTORS = [
    { secret: 'aaaabbbbccccddddeeeeffffgggghhhh', timestamp: 1000000000, body: '{"requestId":"test-id","lead":{}}', sig: 'v1=db8cdda36ab4c15584d39b5a0740d7b5becab5ad6e1afd3ed9ae1432ed2e0787' },
    { secret: 'synthetic-crm-vector-secret-0123456789', timestamp: 1789000000, body: '{"requestId":"9b2f1c3e-7a44-4d1b-8e2f-0c6d5a4b3e21","lead":{"fullName":"Zoë Synthetic","message":"Café ✓ — 日本"}}', sig: 'v1=f7a39ea51d11225dd74c44c3b700631f1cca956c3954a7fd1a10a9fb94af972d' },
    { secret: 'a'.repeat(32), timestamp: 1, body: '', sig: 'v1=d7e1e80175005e5a0612f667167dc14b8e89ad33f167077ff82b91874b5dea0f' },
  ];
  it.each(VECTORS)('matches the CRM signRequest vector and an independent node:crypto HMAC (%#)', async vector => {
    const sig = await signCrmRequest(vector.secret, vector.timestamp, vector.body);
    expect(sig).toBe(vector.sig);
    expect(sig).toBe(nodeSign(vector.secret, vector.timestamp, vector.body));
    expect(sig).toMatch(/^v1=[0-9a-f]{64}$/);
  });

  it('is sensitive to every input: one changed byte in body, timestamp or secret changes the signature', async () => {
    const base = await signCrmRequest(SECRET, 1789000000, '{"a":1}');
    expect(await signCrmRequest(SECRET, 1789000000, '{"a":2}')).not.toBe(base);
    expect(await signCrmRequest(SECRET, 1789000001, '{"a":1}')).not.toBe(base);
    expect(await signCrmRequest(`${SECRET.slice(0, -1)}X`, 1789000000, '{"a":1}')).not.toBe(base);
    // The body is signed exactly as given (no re-serialisation): semantically equal JSON with different bytes differs.
    expect(await signCrmRequest(SECRET, 1789000000, '{"a": 1}')).not.toBe(base);
  });

  it('accepts a secret of exactly 32 characters and rejects 31 (MISSING_SECRET)', async () => {
    await expect(signCrmRequest('s'.repeat(32), 1, 'x')).resolves.toMatch(/^v1=/);
    await expect(signCrmRequest('s'.repeat(31), 1, 'x')).rejects.toThrow(/^MISSING_SECRET$/);
  });

  it.each([
    ['empty secret', '', 1, 'x', 'MISSING_SECRET'],
    ['non-string secret', null, 1, 'x', 'MISSING_SECRET'],
    ['zero timestamp', SECRET, 0, 'x', 'BAD_TIMESTAMP'],
    ['negative timestamp', SECRET, -1, 'x', 'BAD_TIMESTAMP'],
    ['fractional timestamp', SECRET, 1.5, 'x', 'BAD_TIMESTAMP'],
    ['NaN timestamp', SECRET, Number.NaN, 'x', 'BAD_TIMESTAMP'],
    ['Infinity timestamp', SECRET, Number.POSITIVE_INFINITY, 'x', 'BAD_TIMESTAMP'],
    ['unsafe integer timestamp', SECRET, Number.MAX_SAFE_INTEGER + 1, 'x', 'BAD_TIMESTAMP'],
    ['string timestamp', SECRET, '1789000000', 'x', 'BAD_TIMESTAMP'],
    ['null body', SECRET, 1, null, 'BAD_BODY'],
    ['object body', SECRET, 1, { a: 1 }, 'BAD_BODY'],
  ])('rejects %s with %s (same codes and precedence as hmac.mjs)', async (_label, secret, timestamp, body, code) => {
    await expect(signCrmRequest(secret as string, timestamp as number, body as string)).rejects.toThrow(new RegExp(`^${code}$`));
  });

  it('checks the secret before the timestamp and the timestamp before the body', async () => {
    await expect(signCrmRequest('short', 0, null as unknown as string)).rejects.toThrow(/^MISSING_SECRET$/);
    await expect(signCrmRequest(SECRET, 0, null as unknown as string)).rejects.toThrow(/^BAD_TIMESTAMP$/);
  });
});

describe('buildCrmBody', () => {
  it('is exactly JSON.stringify({ requestId, lead: payload }) and preserves the payload key order it is given', () => {
    const payload = { email: 'x@example.invalid', city: 'Orlando', fullName: 'Synthetic Name' };
    expect(buildCrmBody('req-1', payload)).toBe('{"requestId":"req-1","lead":{"email":"x@example.invalid","city":"Orlando","fullName":"Synthetic Name"}}');
    const reordered = { fullName: 'Synthetic Name', city: 'Orlando', email: 'x@example.invalid' };
    expect(buildCrmBody('req-1', reordered)).not.toBe(buildCrmBody('req-1', payload));
  });

  it('escapes non-ASCII and quote characters exactly as JSON.stringify does', () => {
    const payload = { message: 'Café "quoted" ✓\n— 日本' };
    expect(buildCrmBody('r', payload)).toBe(`{"requestId":"r","lead":${JSON.stringify(payload)}}`);
    expect(JSON.parse(buildCrmBody('r', payload)).lead).toEqual(payload);
  });
});

