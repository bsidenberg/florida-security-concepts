describe('crmDependencies().post (wire contract)', () => {
  function client(fetchImpl: (url: string, init: RequestInit) => Promise<Response>, values: Record<string, string> = { FSC_CRM_INTAKE_URL: URL_OK, FSC_CRM_INTAKE_HMAC_SECRET: SECRET }, now: () => number = () => 1789000000) {
    const mock = vi.fn(fetchImpl);
    const deps = crmDependencies(env(values), mock as unknown as typeof fetch, now);
    if (!deps) throw new Error('fixture configuration must be valid');
    return { deps, mock };
  }

  it('POSTs the raw body unchanged to the configured URL with exactly the three headers, redirect:error, cache:no-store and the caller\'s signal', async () => {
    const { deps, mock } = client(async () => jsonResponse(200, { code: 'RECEIVED', receiptId: 'crm-9' }));
    const raw = '{"requestId":"r","lead":{"message":"Café ✓"}}';
    const controller = new AbortController();
    expect(await deps.post(raw, controller.signal)).toEqual({ kind: 'succeeded', receiptId: 'crm-9' });
    expect(mock).toHaveBeenCalledTimes(1);
    const [url, init] = mock.mock.calls[0];
    expect(url).toBe(URL_OK);
    expect(init.method).toBe('POST');
    expect(init.body).toBe(raw);
    expect(init.redirect).toBe('error');
    expect(init.cache).toBe('no-store');
    expect(init.signal).toBe(controller.signal);
    expect(init.headers).toEqual({ 'Content-Type': 'application/json', 'X-FSC-CRM-Timestamp': '1789000000', 'X-FSC-CRM-Signature': nodeSign(SECRET, 1789000000, raw) });
  });

  it('signs with the secret exactly as configured (a secret with internal spaces is used byte-for-byte)', async () => {
    const spaced = 'synthetic secret with internal spaces 0123';
    const { deps, mock } = client(async () => jsonResponse(200, { code: 'RECEIVED' }), { FSC_CRM_INTAKE_URL: URL_OK, FSC_CRM_INTAKE_HMAC_SECRET: spaced });
    await deps.post('{}', new AbortController().signal);
    expect((mock.mock.calls[0][1].headers as Record<string, string>)['X-FSC-CRM-Signature']).toBe(nodeSign(spaced, 1789000000, '{}'));
  });

  it('posts to the normalised pinned URL even when the configured host was uppercase', async () => {
    const { deps, mock } = client(async () => jsonResponse(200, { code: 'RECEIVED' }), { FSC_CRM_INTAKE_URL: URL_OK.replace('izhandnebyywemsjisye.supabase.co', 'IZHANDNEBYYWEMSJISYE.SUPABASE.CO'), FSC_CRM_INTAKE_HMAC_SECRET: SECRET });
    await deps.post('{}', new AbortController().signal);
    expect(mock.mock.calls[0][0]).toBe(URL_OK);
  });

  it('takes a fresh timestamp per call and re-signs; the body bytes are untouched', async () => {
    let now = 1789000000;
    const { deps, mock } = client(async () => jsonResponse(200, { code: 'REPLAYED' }), undefined, () => now);
    await deps.post('{"x":1}', new AbortController().signal);
    now = 1789000007;
    await deps.post('{"x":1}', new AbortController().signal);
    const headers = mock.mock.calls.map(call => call[1].headers as Record<string, string>);
    expect(headers.map(h => h['X-FSC-CRM-Timestamp'])).toEqual(['1789000000', '1789000007']);
    expect(headers.map(h => h['X-FSC-CRM-Signature'])).toEqual([nodeSign(SECRET, 1789000000, '{"x":1}'), nodeSign(SECRET, 1789000007, '{"x":1}')]);
    expect(mock.mock.calls.map(call => call[1].body)).toEqual(['{"x":1}', '{"x":1}']);
  });

  it('the default clock is unix seconds', async () => {
    const mock = vi.fn(async () => jsonResponse(200, { code: 'RECEIVED' }));
    const deps = crmDependencies(VALID, mock as unknown as typeof fetch)!;
    const before = Math.floor(Date.now() / 1000);
    await deps.post('{}', new AbortController().signal);
    const ts = Number(((mock.mock.calls[0] as unknown[])[1] as RequestInit & { headers: Record<string, string> }).headers['X-FSC-CRM-Timestamp']);
    expect(ts).toBeGreaterThanOrEqual(before);
    expect(ts).toBeLessThanOrEqual(Math.floor(Date.now() / 1000));
  });

  it.each([
    ['network error', async () => { throw new TypeError('fetch failed'); }],
    ['abort', async (_url: string, init: RequestInit) => { throw init.signal?.reason ?? new DOMException('aborted', 'AbortError'); }],
    ['redirect refused', async () => { throw new TypeError('fetch failed: redirect mode is set to error'); }],
  ])('%s → ambiguous (never throws)', async (_label, impl) => {
    const { deps } = client(impl as (url: string, init: RequestInit) => Promise<Response>);
    const controller = new AbortController();
    controller.abort();
    await expect(deps.post('{}', controller.signal)).resolves.toEqual({ kind: 'ambiguous' });
  });

  it('unparseable 200 body → classified with a null body → ambiguous; unparseable 409 → conflict', async () => {
    const html = (status: number) => async () => new Response('<html>gateway</html>', { status, headers: { 'content-type': 'text/html' } });
    expect(await client(html(200)).deps.post('{}', new AbortController().signal)).toEqual({ kind: 'ambiguous' });
    expect(await client(html(409)).deps.post('{}', new AbortController().signal)).toEqual({ kind: 'conflict' });
  });

  it('a clock that yields an invalid timestamp is contained as ambiguous without any fetch', async () => {
    const { deps, mock } = client(async () => jsonResponse(200, { code: 'RECEIVED' }), undefined, () => 1.5);
    expect(await deps.post('{}', new AbortController().signal)).toEqual({ kind: 'ambiguous' });
    expect(mock).not.toHaveBeenCalled();
  });

  it('never logs: not the URL, secret, body, signature, timestamp or response', async () => {
    const spies = (['log', 'info', 'warn', 'error', 'debug'] as const).map(method => vi.spyOn(console, method).mockImplementation(() => undefined));
    const raw = '{"requestId":"r","lead":{"email":"log-probe@example.invalid"}}';
    for (const impl of [async () => jsonResponse(200, { code: 'RECEIVED', receiptId: 'crm-log-probe' }), async () => jsonResponse(503, { error: 'crm-body-probe' }), async () => { throw new TypeError('fetch failed'); }]) {
      await client(impl).deps.post(raw, new AbortController().signal);
    }
    expect(spies.reduce((total, spy) => total + spy.mock.calls.length, 0)).toBe(0);
  });
});
